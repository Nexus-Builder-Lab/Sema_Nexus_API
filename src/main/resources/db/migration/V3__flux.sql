-- ---------------------------------------------------------------------
-- NUMERACAO_DEMANDA — último sequencial usado por ano (número DEM-AAAA/NNNN).
-- A geração faz SELECT ... FOR UPDATE nesta linha (lock pessimista), serializando cadastros concorrentes.
-- ---------------------------------------------------------------------
CREATE TABLE NUMERACAO_DEMANDA (
    ANO     NUMBER(4)  NOT NULL,
    ULTIMO  NUMBER(9)  DEFAULT 0 NOT NULL,
    CONSTRAINT PK_NUMERACAO_DEMANDA PRIMARY KEY (ANO),
    CONSTRAINT CK_NUMERACAO_DEMANDA_ANO CHECK (ANO BETWEEN 2000 AND 2999),
    CONSTRAINT CK_NUMERACAO_DEMANDA_ULTIMO CHECK (ULTIMO >= 0)
);

-- ---------------------------------------------------------------------
-- DEMANDA — exclusão lógica por EXCLUIDO_EM. "Atrasada" é derivada (PRAZO < hoje e STATUS <> FINALIZADA).
-- ---------------------------------------------------------------------
CREATE TABLE DEMANDA (
    ID                       NUMBER(19)         GENERATED BY DEFAULT AS IDENTITY,
    NUMERO                   VARCHAR2(20)       NOT NULL,
    TITULO                   VARCHAR2(200 CHAR) NOT NULL,
    DESCRICAO                CLOB               NOT NULL,
    ORIGEM                   VARCHAR2(30)       NOT NULL,
    CATEGORIA                VARCHAR2(40),
    MUNICIPIO_ID             NUMBER(7)          NOT NULL,
    LOCALIDADE               VARCHAR2(200 CHAR),
    LATITUDE                 NUMBER(9,6),
    LONGITUDE                NUMBER(9,6),
    DATA_RECEBIMENTO         DATE               NOT NULL,
    PRIORIDADE               VARCHAR2(10),
    PRAZO_SUGERIDO           DATE,
    PRAZO                    DATE,
    STATUS                   VARCHAR2(30)       DEFAULT 'PENDENTE' NOT NULL,
    EQUIPE_ID                NUMBER(19),
    FISCAL_ID                NUMBER(19),
    OBSERVACOES              VARCHAR2(2000 CHAR),
    RESULTADO_FINAL          CLOB,
    JUSTIFICATIVA_CONCLUSAO  VARCHAR2(2000 CHAR),
    CONCLUIDA_EM             TIMESTAMP,
    CRIADO_POR               NUMBER(19)         NOT NULL,
    CRIADO_EM                TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
    ATUALIZADO_EM            TIMESTAMP,
    EXCLUIDO_EM              TIMESTAMP,
    CONSTRAINT PK_DEMANDA PRIMARY KEY (ID),
    CONSTRAINT UK_DEMANDA_NUMERO UNIQUE (NUMERO),
    CONSTRAINT CK_DEMANDA_NUMERO CHECK (REGEXP_LIKE(NUMERO, '^DEM-[0-9]{4}/[0-9]{4,}$')),
    CONSTRAINT CK_DEMANDA_ORIGEM CHECK (ORIGEM IN (
        'DENUNCIA', 'MONITORAMENTO', 'SOLICITACAO_INSTITUCIONAL', 'ACAO_PLANEJADA', 'ANALISE_AMBIENTAL')),
    CONSTRAINT CK_DEMANDA_CATEGORIA CHECK (CATEGORIA IS NULL OR CATEGORIA IN (
        'DESMATAMENTO_ILEGAL', 'QUEIMADA_INCENDIO', 'RECURSOS_HIDRICOS', 'FAUNA_SILVESTRE', 'PESCA_IRREGULAR',
        'MINERACAO_IRREGULAR', 'RESIDUOS_POLUICAO', 'AREA_PRESERVACAO_PERMANENTE')),
    CONSTRAINT CK_DEMANDA_PRIORIDADE CHECK (PRIORIDADE IS NULL OR PRIORIDADE IN ('BAIXA', 'MEDIA', 'ALTA', 'URGENTE')),
    CONSTRAINT CK_DEMANDA_STATUS CHECK (STATUS IN (
        'PENDENTE', 'EM_TRIAGEM', 'AGUARDANDO_DISTRIBUICAO', 'DISTRIBUIDA', 'EM_ANDAMENTO',
        'AGUARDANDO_CONCLUSAO', 'FINALIZADA')),
    CONSTRAINT CK_DEMANDA_LATITUDE CHECK (LATITUDE IS NULL OR LATITUDE BETWEEN -18.1 AND -7.3),
    CONSTRAINT CK_DEMANDA_LONGITUDE CHECK (LONGITUDE IS NULL OR LONGITUDE BETWEEN -61.7 AND -50.2),
    CONSTRAINT CK_DEMANDA_COORDENADAS CHECK ((LATITUDE IS NULL AND LONGITUDE IS NULL)
        OR (LATITUDE IS NOT NULL AND LONGITUDE IS NOT NULL)),
    CONSTRAINT FK_DEMANDA_MUNICIPIO FOREIGN KEY (MUNICIPIO_ID) REFERENCES MUNICIPIO (ID),
    CONSTRAINT FK_DEMANDA_EQUIPE FOREIGN KEY (EQUIPE_ID) REFERENCES EQUIPE (ID),
    CONSTRAINT FK_DEMANDA_FISCAL FOREIGN KEY (FISCAL_ID) REFERENCES USUARIO (ID),
    CONSTRAINT FK_DEMANDA_CRIADO_POR FOREIGN KEY (CRIADO_POR) REFERENCES USUARIO (ID)
);
CREATE INDEX IX_DEMANDA_STATUS ON DEMANDA (STATUS);
CREATE INDEX IX_DEMANDA_MUNICIPIO_ID ON DEMANDA (MUNICIPIO_ID);
CREATE INDEX IX_DEMANDA_CATEGORIA ON DEMANDA (CATEGORIA);
CREATE INDEX IX_DEMANDA_DATA_RECEBIMENTO ON DEMANDA (DATA_RECEBIMENTO);
CREATE INDEX IX_DEMANDA_EQUIPE_ID ON DEMANDA (EQUIPE_ID);
CREATE INDEX IX_DEMANDA_FISCAL_ID ON DEMANDA (FISCAL_ID);
CREATE INDEX IX_DEMANDA_PRAZO ON DEMANDA (PRAZO);
CREATE INDEX IX_DEMANDA_CRIADO_POR ON DEMANDA (CRIADO_POR);

-- ---------------------------------------------------------------------
-- DEMANDA_HISTORICO — linha do tempo (append-only) da demanda.
-- ---------------------------------------------------------------------
CREATE TABLE DEMANDA_HISTORICO (
    ID               NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY,
    DEMANDA_ID       NUMBER(19)    NOT NULL,
    TIPO             VARCHAR2(20)  NOT NULL,
    STATUS_ANTERIOR  VARCHAR2(30),
    STATUS_NOVO      VARCHAR2(30),
    TEXTO            VARCHAR2(2000 CHAR),
    USUARIO_ID       NUMBER(19)    NOT NULL,
    DATA             TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_DEMANDA_HISTORICO PRIMARY KEY (ID),
    CONSTRAINT CK_DEMANDA_HIST_TIPO CHECK (TIPO IN (
        'CADASTRO', 'EDICAO', 'TRIAGEM', 'COMPLEMENTACAO', 'DISTRIBUICAO', 'INICIO', 'ATIVIDADE',
        'FISCALIZACAO', 'CONCLUSAO', 'DEVOLUCAO', 'DOCUMENTO', 'EXCLUSAO')),
    CONSTRAINT CK_DEMANDA_HIST_STATUS_ANT CHECK (STATUS_ANTERIOR IS NULL OR STATUS_ANTERIOR IN (
        'PENDENTE', 'EM_TRIAGEM', 'AGUARDANDO_DISTRIBUICAO', 'DISTRIBUIDA', 'EM_ANDAMENTO',
        'AGUARDANDO_CONCLUSAO', 'FINALIZADA')),
    CONSTRAINT CK_DEMANDA_HIST_STATUS_NOVO CHECK (STATUS_NOVO IS NULL OR STATUS_NOVO IN (
        'PENDENTE', 'EM_TRIAGEM', 'AGUARDANDO_DISTRIBUICAO', 'DISTRIBUIDA', 'EM_ANDAMENTO',
        'AGUARDANDO_CONCLUSAO', 'FINALIZADA')),
    CONSTRAINT FK_DEMANDA_HIST_DEMANDA FOREIGN KEY (DEMANDA_ID) REFERENCES DEMANDA (ID),
    CONSTRAINT FK_DEMANDA_HIST_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO (ID)
);
CREATE INDEX IX_DEMANDA_HIST_DEMANDA_DATA ON DEMANDA_HISTORICO (DEMANDA_ID, DATA);
CREATE INDEX IX_DEMANDA_HIST_USUARIO_ID ON DEMANDA_HISTORICO (USUARIO_ID);

-- ---------------------------------------------------------------------
-- DISTRIBUICAO — histórico de (re)distribuições (usada pela Issue #12).
-- ---------------------------------------------------------------------
CREATE TABLE DISTRIBUICAO (
    ID           NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY,
    DEMANDA_ID   NUMBER(19)    NOT NULL,
    EQUIPE_ID    NUMBER(19)    NOT NULL,
    FISCAL_ID    NUMBER(19)    NOT NULL,
    DATA         TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    PRAZO        DATE          NOT NULL,
    OBSERVACOES  VARCHAR2(2000 CHAR),
    USUARIO_ID   NUMBER(19)    NOT NULL,
    CONSTRAINT PK_DISTRIBUICAO PRIMARY KEY (ID),
    CONSTRAINT FK_DISTRIBUICAO_DEMANDA FOREIGN KEY (DEMANDA_ID) REFERENCES DEMANDA (ID),
    CONSTRAINT FK_DISTRIBUICAO_EQUIPE FOREIGN KEY (EQUIPE_ID) REFERENCES EQUIPE (ID),
    CONSTRAINT FK_DISTRIBUICAO_FISCAL FOREIGN KEY (FISCAL_ID) REFERENCES USUARIO (ID),
    CONSTRAINT FK_DISTRIBUICAO_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO (ID)
);
CREATE INDEX IX_DISTRIBUICAO_DEMANDA_ID ON DISTRIBUICAO (DEMANDA_ID);
CREATE INDEX IX_DISTRIBUICAO_EQUIPE_ID ON DISTRIBUICAO (EQUIPE_ID);
CREATE INDEX IX_DISTRIBUICAO_FISCAL_ID ON DISTRIBUICAO (FISCAL_ID);
CREATE INDEX IX_DISTRIBUICAO_USUARIO_ID ON DISTRIBUICAO (USUARIO_ID);

-- ---------------------------------------------------------------------
-- FISCALIZACAO — registro simulado de fiscalização, 1:1 com a demanda no MVP (usada pela Issue #13).
-- ---------------------------------------------------------------------
CREATE TABLE FISCALIZACAO (
    ID              NUMBER(19)  GENERATED BY DEFAULT AS IDENTITY,
    DEMANDA_ID      NUMBER(19)  NOT NULL,
    DATA            DATE        NOT NULL,
    EQUIPE_ID       NUMBER(19)  NOT NULL,
    ATIVIDADES      CLOB        NOT NULL,
    RESULTADO       CLOB        NOT NULL,
    EVIDENCIAS      CLOB        NOT NULL,
    RECOMENDACOES   CLOB,
    REGISTRADO_POR  NUMBER(19)  NOT NULL,
    REGISTRADO_EM   TIMESTAMP   DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_FISCALIZACAO PRIMARY KEY (ID),
    CONSTRAINT UK_FISCALIZACAO_DEMANDA UNIQUE (DEMANDA_ID),
    CONSTRAINT FK_FISCALIZACAO_DEMANDA FOREIGN KEY (DEMANDA_ID) REFERENCES DEMANDA (ID),
    CONSTRAINT FK_FISCALIZACAO_EQUIPE FOREIGN KEY (EQUIPE_ID) REFERENCES EQUIPE (ID),
    CONSTRAINT FK_FISCALIZACAO_REGISTRADO_POR FOREIGN KEY (REGISTRADO_POR) REFERENCES USUARIO (ID)
);
CREATE INDEX IX_FISCALIZACAO_EQUIPE_ID ON FISCALIZACAO (EQUIPE_ID);
CREATE INDEX IX_FISCALIZACAO_REGISTRADO_POR ON FISCALIZACAO (REGISTRADO_POR);
