-- GH-34: camada de referência com dados PÚBLICOS do INPE (focos de calor e alertas DETER) de Mato Grosso.
-- Exceção de escopo aprovada: dados reais e abertos, mantidos separados das demandas fictícias do Flux.
CREATE TABLE IMPORTACAO_REFERENCIA (
    ID            NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
    FONTE         VARCHAR2(200 CHAR)  NOT NULL,
    TIPO          VARCHAR2(20)        NOT NULL,
    PERIODO_DE    DATE                NOT NULL,
    PERIODO_ATE   DATE                NOT NULL,
    IMPORTADO_EM  TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    REGISTROS     NUMBER(10)          DEFAULT 0 NOT NULL,
    URL_ORIGEM    VARCHAR2(500 CHAR)  NOT NULL,
    LICENCA       VARCHAR2(500 CHAR)  NOT NULL,
    ARQUIVO       VARCHAR2(200 CHAR)  NOT NULL,
    SHA256        CHAR(64)            NOT NULL,
    CONSTRAINT PK_IMPORTACAO_REFERENCIA PRIMARY KEY (ID),
    CONSTRAINT UQ_IMPORTACAO_REF_SHA256 UNIQUE (SHA256),
    CONSTRAINT CK_IMPORTACAO_REF_TIPO CHECK (TIPO IN ('FOCO_CALOR', 'DESMATAMENTO')),
    CONSTRAINT CK_IMPORTACAO_REF_PERIODO CHECK (PERIODO_ATE >= PERIODO_DE)
);

CREATE TABLE REFERENCIA_SATELITE (
    ID            NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
    IMPORTACAO_ID NUMBER(19)          NOT NULL,
    TIPO          VARCHAR2(20)        NOT NULL,
    DATA_HORA     TIMESTAMP           NOT NULL,
    LATITUDE      NUMBER(9,6)         NOT NULL,
    LONGITUDE     NUMBER(9,6)         NOT NULL,
    MUNICIPIO_ID  NUMBER(7)           NOT NULL,
    BIOMA         VARCHAR2(20)        NOT NULL,
    SATELITE      VARCHAR2(60 CHAR),
    CLASSE        VARCHAR2(60 CHAR),
    AREA_KM2      NUMBER(12,4),
    ATRIBUTOS     CLOB,
    CONSTRAINT PK_REFERENCIA_SATELITE PRIMARY KEY (ID),
    CONSTRAINT FK_REFSAT_IMPORTACAO FOREIGN KEY (IMPORTACAO_ID) REFERENCES IMPORTACAO_REFERENCIA (ID),
    CONSTRAINT FK_REFSAT_MUNICIPIO FOREIGN KEY (MUNICIPIO_ID) REFERENCES MUNICIPIO (ID),
    CONSTRAINT CK_REFSAT_TIPO CHECK (TIPO IN ('FOCO_CALOR', 'DESMATAMENTO')),
    CONSTRAINT CK_REFSAT_BIOMA CHECK (BIOMA IN ('AMAZONIA', 'CERRADO', 'PANTANAL')),
    CONSTRAINT CK_REFSAT_LATITUDE CHECK (LATITUDE BETWEEN -18.1 AND -7.3),
    CONSTRAINT CK_REFSAT_LONGITUDE CHECK (LONGITUDE BETWEEN -61.7 AND -50.1)
);
CREATE INDEX IX_REFSAT_TIPO_DATA ON REFERENCIA_SATELITE (TIPO, DATA_HORA);
CREATE INDEX IX_REFSAT_MUNICIPIO ON REFERENCIA_SATELITE (MUNICIPIO_ID);
CREATE INDEX IX_REFSAT_IMPORTACAO ON REFERENCIA_SATELITE (IMPORTACAO_ID);
