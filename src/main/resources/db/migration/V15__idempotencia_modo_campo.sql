-- GH-147 (PE-11C-API): idempotência para sincronização do modo campo (início, atividades e fiscalização).
-- Evita duplicidade em reenvios por (usuário, operação, demanda, chave) e detecta reutilização da mesma chave
-- com conteúdo divergente (409 problem+json). Registros expirados são substituídos ou removidos pela limpeza diária.
CREATE TABLE CHAVE_IDEMPOTENCIA (
    ID               NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
    USUARIO_ID       NUMBER(19)          NOT NULL,
    DEMANDA_ID       NUMBER(19)          NOT NULL,
    OPERACAO         VARCHAR2(30)        NOT NULL,
    CHAVE            VARCHAR2(128 CHAR)  NOT NULL,
    HASH_REQUISICAO  VARCHAR2(64)        NOT NULL,
    STATUS_HTTP      NUMBER(3)           NOT NULL,
    CORPO_RESPOSTA   CLOB                NOT NULL,
    CONCLUIDA        BOOLEAN             DEFAULT TRUE NOT NULL,
    CRIADO_EM        TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    EXPIRA_EM        TIMESTAMP           NOT NULL,
    CONSTRAINT PK_CHAVE_IDEMPOTENCIA PRIMARY KEY (ID),
    CONSTRAINT UK_CHAVE_IDEMP_ESCOPO UNIQUE (USUARIO_ID, OPERACAO, DEMANDA_ID, CHAVE),
    CONSTRAINT CK_CHAVE_IDEMP_OPERACAO CHECK (OPERACAO IN ('INICIO', 'ATIVIDADE', 'FISCALIZACAO')),
    CONSTRAINT CK_CHAVE_IDEMP_CHAVE CHECK (REGEXP_LIKE(CHAVE, '^[A-Za-z0-9._:-]{1,128}$')),
    CONSTRAINT CK_CHAVE_IDEMP_HASH CHECK (REGEXP_LIKE(HASH_REQUISICAO, '^[0-9a-f]{64}$')),
    CONSTRAINT CK_CHAVE_IDEMP_STATUS CHECK (STATUS_HTTP BETWEEN 200 AND 299),
    CONSTRAINT CK_CHAVE_IDEMP_JSON CHECK (CORPO_RESPOSTA IS JSON),
    CONSTRAINT FK_CHAVE_IDEMP_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO (ID),
    CONSTRAINT FK_CHAVE_IDEMP_DEMANDA FOREIGN KEY (DEMANDA_ID) REFERENCES DEMANDA (ID)
);

CREATE INDEX IX_CHAVE_IDEMP_DEMANDA ON CHAVE_IDEMPOTENCIA (DEMANDA_ID);
CREATE INDEX IX_CHAVE_IDEMP_EXPIRA ON CHAVE_IDEMPOTENCIA (EXPIRA_EM);
