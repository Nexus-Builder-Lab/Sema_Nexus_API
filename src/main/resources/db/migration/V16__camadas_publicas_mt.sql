-- GH-144: Camadas públicas abertas offline de Mato Grosso (UCs MMA/CNUC, Terras Indígenas FUNAI e hidrografia principal ANA).
-- Dados reais públicos com fonte, licença, data de referência e oficialSema=false, mantidos separados das demandas fictícias do Flux.

CREATE TABLE IMPORTACAO_CAMADA_PUBLICA (
    ID               NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
    CAMADA           VARCHAR2(30)        NOT NULL,
    FONTE            VARCHAR2(200 CHAR)  NOT NULL,
    DATA_REFERENCIA  DATE                NOT NULL,
    IMPORTADO_EM     TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    REGISTROS        NUMBER(10)          DEFAULT 0 NOT NULL,
    URL_ORIGEM       VARCHAR2(500 CHAR)  NOT NULL,
    LICENCA          VARCHAR2(500 CHAR)  NOT NULL,
    ARQUIVO          VARCHAR2(200 CHAR)  NOT NULL,
    SHA256           CHAR(64)            NOT NULL,
    CONSTRAINT PK_IMPORTACAO_CAMADA_PUBLICA PRIMARY KEY (ID),
    CONSTRAINT UQ_IMP_CAMPUB_SHA256 UNIQUE (SHA256),
    CONSTRAINT CK_IMP_CAMPUB_CAMADA CHECK (CAMADA IN ('UNIDADE_CONSERVACAO', 'TERRA_INDIGENA', 'HIDROGRAFIA'))
);

CREATE TABLE CAMADA_PUBLICA_FEICAO (
    ID               NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
    IMPORTACAO_ID    NUMBER(19)          NOT NULL,
    CAMADA           VARCHAR2(30)        NOT NULL,
    CODIGO_ORIGEM    VARCHAR2(80 CHAR),
    NOME             VARCHAR2(300 CHAR)  NOT NULL,
    CATEGORIA        VARCHAR2(150 CHAR),
    ESFERA           VARCHAR2(80 CHAR),
    AREA_HA          NUMBER(14,2),
    CENTROID_LAT     NUMBER(9,6)         NOT NULL,
    CENTROID_LON     NUMBER(9,6)         NOT NULL,
    LAT_MIN          NUMBER(9,6)         NOT NULL,
    LAT_MAX          NUMBER(9,6)         NOT NULL,
    LON_MIN          NUMBER(9,6)         NOT NULL,
    LON_MAX          NUMBER(9,6)         NOT NULL,
    TIPO_GEOMETRIA   VARCHAR2(30)        NOT NULL,
    ATRIBUTOS        CLOB,
    GEOMETRIA        CLOB                NOT NULL,
    CONSTRAINT PK_CAMADA_PUBLICA_FEICAO PRIMARY KEY (ID),
    CONSTRAINT FK_CAMPUB_IMPORTACAO FOREIGN KEY (IMPORTACAO_ID) REFERENCES IMPORTACAO_CAMADA_PUBLICA (ID),
    CONSTRAINT CK_CAMPUB_CAMADA CHECK (CAMADA IN ('UNIDADE_CONSERVACAO', 'TERRA_INDIGENA', 'HIDROGRAFIA')),
    CONSTRAINT CK_CAMPUB_TIPO_GEOM CHECK (TIPO_GEOMETRIA IN ('Polygon', 'MultiPolygon', 'LineString', 'MultiLineString')),
    CONSTRAINT CK_CAMPUB_AREA_HA CHECK (AREA_HA IS NULL OR AREA_HA >= 0),
    CONSTRAINT CK_CAMPUB_LAT CHECK (CENTROID_LAT BETWEEN -90 AND 90),
    CONSTRAINT CK_CAMPUB_LON CHECK (CENTROID_LON BETWEEN -180 AND 180)
);

CREATE INDEX IX_CAMPUB_CAMADA ON CAMADA_PUBLICA_FEICAO (CAMADA);
CREATE INDEX IX_CAMPUB_IMPORTACAO ON CAMADA_PUBLICA_FEICAO (IMPORTACAO_ID);
CREATE INDEX IX_CAMPUB_BBOX ON CAMADA_PUBLICA_FEICAO (CAMADA, LAT_MIN, LAT_MAX, LON_MIN, LON_MAX);
