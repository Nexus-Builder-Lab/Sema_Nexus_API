-- GH-25: notificações por usuário (nova demanda, distribuição, documento, prazo próximo e atraso).
-- CHAVE evita duplicidade (ex.: PRAZO:<demanda>:<data> gera no máximo uma notificação por usuário/dia).
CREATE TABLE NOTIFICACAO (
    ID          NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
    USUARIO_ID  NUMBER(19)          NOT NULL,
    TIPO        VARCHAR2(30)        NOT NULL,
    TITULO      VARCHAR2(200 CHAR)  NOT NULL,
    MENSAGEM    VARCHAR2(1000 CHAR) NOT NULL,
    DEMANDA_ID  NUMBER(19),
    CHAVE       VARCHAR2(120 CHAR)  NOT NULL,
    LIDA        BOOLEAN             DEFAULT FALSE NOT NULL,
    CRIADA_EM   TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    LIDA_EM     TIMESTAMP,
    CONSTRAINT PK_NOTIFICACAO PRIMARY KEY (ID),
    CONSTRAINT FK_NOTIFICACAO_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO (ID),
    CONSTRAINT FK_NOTIFICACAO_DEMANDA FOREIGN KEY (DEMANDA_ID) REFERENCES DEMANDA (ID),
    CONSTRAINT UQ_NOTIFICACAO_CHAVE UNIQUE (USUARIO_ID, CHAVE),
    CONSTRAINT CK_NOTIFICACAO_TIPO CHECK (TIPO IN (
        'NOVA_DEMANDA', 'DISTRIBUICAO', 'DOCUMENTO_VINCULADO', 'PRAZO_PROXIMO', 'DEMANDA_ATRASADA'))
);

CREATE INDEX IX_NOTIFICACAO_USUARIO ON NOTIFICACAO (USUARIO_ID, LIDA, CRIADA_EM);
CREATE INDEX IX_NOTIFICACAO_DEMANDA ON NOTIFICACAO (DEMANDA_ID);
