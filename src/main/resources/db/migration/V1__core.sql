-- ---------------------------------------------------------------------
-- MUNICIPIO — referência geográfica pública (IBGE, UF 51). PK = código IBGE.
-- ---------------------------------------------------------------------
CREATE TABLE MUNICIPIO (
    ID          NUMBER(7)     NOT NULL,
    NOME        VARCHAR2(100) NOT NULL,
    REGIAO      VARCHAR2(60)  NOT NULL,
    BIOMA       VARCHAR2(20)  NOT NULL,
    LATITUDE    NUMBER(9,6)   NOT NULL,
    LONGITUDE   NUMBER(9,6)   NOT NULL,
    CONSTRAINT PK_MUNICIPIO PRIMARY KEY (ID),
    CONSTRAINT CK_MUNICIPIO_UF_MT CHECK (ID BETWEEN 5100000 AND 5199999),
    CONSTRAINT CK_MUNICIPIO_BIOMA CHECK (BIOMA IN ('AMAZONIA', 'CERRADO', 'PANTANAL')),
    CONSTRAINT CK_MUNICIPIO_LATITUDE CHECK (LATITUDE BETWEEN -18.1 AND -7.3),
    CONSTRAINT CK_MUNICIPIO_LONGITUDE CHECK (LONGITUDE BETWEEN -61.7 AND -50.1)
);
CREATE INDEX IX_MUNICIPIO_BIOMA ON MUNICIPIO (BIOMA);
CREATE INDEX IX_MUNICIPIO_REGIAO ON MUNICIPIO (REGIAO);

-- ---------------------------------------------------------------------
-- SETOR
-- ---------------------------------------------------------------------
CREATE TABLE SETOR (
    ID              NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY,
    SIGLA           VARCHAR2(20)  NOT NULL,
    NOME            VARCHAR2(150) NOT NULL,
    ATIVO           BOOLEAN       DEFAULT TRUE NOT NULL,
    CRIADO_EM       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    ATUALIZADO_EM   TIMESTAMP,
    CONSTRAINT PK_SETOR PRIMARY KEY (ID),
    CONSTRAINT UK_SETOR_SIGLA UNIQUE (SIGLA)
);

-- ---------------------------------------------------------------------
-- USUARIO — senha somente como hash BCrypt. E-mail sempre minúsculo.
-- ---------------------------------------------------------------------
CREATE TABLE USUARIO (
    ID              NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY,
    NOME            VARCHAR2(150) NOT NULL,
    EMAIL           VARCHAR2(254) NOT NULL,
    SENHA_HASH      VARCHAR2(100) NOT NULL,
    PERFIL          VARCHAR2(20)  NOT NULL,
    SETOR_ID        NUMBER(19),
    ATIVO           BOOLEAN       DEFAULT TRUE NOT NULL,
    ULTIMO_ACESSO   TIMESTAMP,
    DEMO            BOOLEAN       DEFAULT FALSE NOT NULL,
    CRIADO_EM       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    ATUALIZADO_EM   TIMESTAMP,
    CONSTRAINT PK_USUARIO PRIMARY KEY (ID),
    CONSTRAINT UK_USUARIO_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USUARIO_EMAIL_MINUSCULO CHECK (EMAIL = LOWER(EMAIL)),
    CONSTRAINT CK_USUARIO_PERFIL CHECK (PERFIL IN ('ADMIN', 'GESTOR', 'FISCAL', 'ANALISTA', 'CONSULTA')),
    CONSTRAINT FK_USUARIO_SETOR FOREIGN KEY (SETOR_ID) REFERENCES SETOR (ID)
);
CREATE INDEX IX_USUARIO_SETOR_ID ON USUARIO (SETOR_ID);
CREATE INDEX IX_USUARIO_PERFIL ON USUARIO (PERFIL);

-- ---------------------------------------------------------------------
-- EQUIPE e EQUIPE_MEMBRO
-- ---------------------------------------------------------------------
CREATE TABLE EQUIPE (
    ID              NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY,
    NOME            VARCHAR2(150) NOT NULL,
    SETOR_ID        NUMBER(19)    NOT NULL,
    RESPONSAVEL_ID  NUMBER(19),
    ATIVO           BOOLEAN       DEFAULT TRUE NOT NULL,
    CRIADO_EM       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    ATUALIZADO_EM   TIMESTAMP,
    CONSTRAINT PK_EQUIPE PRIMARY KEY (ID),
    CONSTRAINT UK_EQUIPE_SETOR_NOME UNIQUE (SETOR_ID, NOME),
    CONSTRAINT FK_EQUIPE_SETOR FOREIGN KEY (SETOR_ID) REFERENCES SETOR (ID),
    CONSTRAINT FK_EQUIPE_RESPONSAVEL FOREIGN KEY (RESPONSAVEL_ID) REFERENCES USUARIO (ID)
);
CREATE INDEX IX_EQUIPE_RESPONSAVEL_ID ON EQUIPE (RESPONSAVEL_ID);

CREATE TABLE EQUIPE_MEMBRO (
    EQUIPE_ID   NUMBER(19) NOT NULL,
    USUARIO_ID  NUMBER(19) NOT NULL,
    CONSTRAINT PK_EQUIPE_MEMBRO PRIMARY KEY (EQUIPE_ID, USUARIO_ID),
    CONSTRAINT FK_EQUIPE_MEMBRO_EQUIPE FOREIGN KEY (EQUIPE_ID) REFERENCES EQUIPE (ID) ON DELETE CASCADE,
    CONSTRAINT FK_EQUIPE_MEMBRO_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO (ID)
);
CREATE INDEX IX_EQUIPE_MEMBRO_USUARIO_ID ON EQUIPE_MEMBRO (USUARIO_ID);

-- ---------------------------------------------------------------------
-- AUDITORIA — registro append-only das operações (consulta: Issue #14).
-- ---------------------------------------------------------------------
CREATE TABLE AUDITORIA (
    ID           NUMBER(19)     GENERATED BY DEFAULT AS IDENTITY,
    DATA         TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    USUARIO_ID   NUMBER(19),
    ACAO         VARCHAR2(60)   NOT NULL,
    ENTIDADE     VARCHAR2(60)   NOT NULL,
    ENTIDADE_ID  VARCHAR2(64),
    DETALHE      VARCHAR2(4000),
    CONSTRAINT PK_AUDITORIA PRIMARY KEY (ID),
    CONSTRAINT FK_AUDITORIA_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO (ID)
);
CREATE INDEX IX_AUDITORIA_DATA ON AUDITORIA (DATA);
CREATE INDEX IX_AUDITORIA_ENTIDADE ON AUDITORIA (ENTIDADE, ENTIDADE_ID);
CREATE INDEX IX_AUDITORIA_USUARIO_ID ON AUDITORIA (USUARIO_ID);
