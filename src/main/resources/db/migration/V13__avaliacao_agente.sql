-- GH-131: governança de IA — concordância Humano × IA e feedback do Assistente DocIA.
-- Uma linha por sugestão de agente (triagem/distribuição) ou resposta do DocIA. Nasce PENDENTE; vira
-- ACEITA_INTEGRAL / AJUSTADA_PARCIAL / DESCARTADA quando a pessoa conclui a triagem ou a distribuição
-- (campos sugeridos × aplicados), ou UTIL / IMPRECISA quando o autor da pergunta avalia a resposta.
-- Só a sugestão mais recente por demanda/agente fica PENDENTE. Não depende de objetos de outras migrations além da V1/V3.
CREATE TABLE AVALIACAO_AGENTE (
    ID                  NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
    AGENTE              VARCHAR2(30)        NOT NULL,
    DEMANDA_ID          NUMBER(19),
    EXECUCAO_ID         VARCHAR2(36 CHAR),
    USUARIO_ID          NUMBER(19)          NOT NULL,
    MODO                VARCHAR2(20),
    SUGERIDO            VARCHAR2(1000 CHAR),
    APLICADO            VARCHAR2(1000 CHAR),
    RESULTADO           VARCHAR2(20)        NOT NULL,
    CAMPOS_DIVERGENTES  VARCHAR2(200 CHAR),
    CATEGORIA           VARCHAR2(40),
    AVALIADOR_ID        NUMBER(19),
    CRIADO_EM           TIMESTAMP           NOT NULL,
    AVALIADO_EM         TIMESTAMP,
    CONSTRAINT PK_AVALIACAO_AGENTE PRIMARY KEY (ID),
    CONSTRAINT FK_AVALIACAO_AGENTE_DEMANDA FOREIGN KEY (DEMANDA_ID) REFERENCES DEMANDA (ID),
    CONSTRAINT FK_AVALIACAO_AGENTE_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO (ID),
    CONSTRAINT FK_AVALIACAO_AGENTE_AVALIADOR FOREIGN KEY (AVALIADOR_ID) REFERENCES USUARIO (ID),
    CONSTRAINT UQ_AVALIACAO_AGENTE_EXECUCAO UNIQUE (EXECUCAO_ID),
    CONSTRAINT CK_AVALIACAO_AGENTE_AGENTE CHECK (AGENTE IN ('triagem', 'distribuicao', 'docia')),
    CONSTRAINT CK_AVALIACAO_AGENTE_RESULTADO CHECK (RESULTADO IN (
        'PENDENTE', 'ACEITA_INTEGRAL', 'AJUSTADA_PARCIAL', 'DESCARTADA', 'UTIL', 'IMPRECISA'))
);

CREATE INDEX IX_AVALIACAO_AGENTE_DEMANDA ON AVALIACAO_AGENTE (DEMANDA_ID, AGENTE, RESULTADO);
CREATE INDEX IX_AVALIACAO_AGENTE_PERIODO ON AVALIACAO_AGENTE (AVALIADO_EM, AGENTE);
CREATE INDEX IX_AVALIACAO_AGENTE_USUARIO ON AVALIACAO_AGENTE (USUARIO_ID);
CREATE INDEX IX_AVALIACAO_AGENTE_AVALIADOR ON AVALIACAO_AGENTE (AVALIADOR_ID);
