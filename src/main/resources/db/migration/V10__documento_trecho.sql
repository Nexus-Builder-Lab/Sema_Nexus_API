-- GH-141: busca híbrida do DocIA (Oracle Database 23ai, tipo VECTOR).
-- AMBIENTE DEMONSTRATIVO — DADOS FICTÍCIOS. Este arquivo só cria estrutura; os trechos são gerados pela API.
-- Cada documento é dividido em trechos (chunks) com o embedding do modelo local (nomic-embed-text: 768 dimensões,
-- FLOAT32). A tabela é derivada do DOCUMENTO: pode ser apagada e reconstruída a qualquer momento pela API
-- (indexação idempotente ao iniciar). Busca vetorial exata (VECTOR_DISTANCE COSINE): o acervo demonstrativo é
-- pequeno, então não há índice vetorial (HNSW/IVF exigiriam VECTOR_MEMORY_SIZE no banco).
CREATE TABLE DOCUMENTO_TRECHO (
    ID            NUMBER(19)           GENERATED BY DEFAULT AS IDENTITY,
    DOCUMENTO_ID  NUMBER(19)           NOT NULL,
    ORDEM         NUMBER(5)            NOT NULL,
    TEXTO         VARCHAR2(2000 CHAR)  NOT NULL,
    EMBEDDING     VECTOR(768, FLOAT32) NOT NULL,
    MODELO        VARCHAR2(100 CHAR)   NOT NULL,
    CRIADO_EM     TIMESTAMP            DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_DOCUMENTO_TRECHO PRIMARY KEY (ID),
    CONSTRAINT UK_DOCUMENTO_TRECHO UNIQUE (DOCUMENTO_ID, MODELO, ORDEM),
    CONSTRAINT FK_DOCTRECHO_DOCUMENTO FOREIGN KEY (DOCUMENTO_ID) REFERENCES DOCUMENTO (ID) ON DELETE CASCADE,
    CONSTRAINT CK_DOCTRECHO_ORDEM CHECK (ORDEM >= 0)
);

CREATE INDEX IX_DOCTRECHO_MODELO ON DOCUMENTO_TRECHO (MODELO, DOCUMENTO_ID);
