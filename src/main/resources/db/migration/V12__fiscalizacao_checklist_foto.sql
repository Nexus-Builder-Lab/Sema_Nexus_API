-- AMBIENTE DEMONSTRATIVO — DADOS FICTÍCIOS. Simulação: não gera auto de infração nem substitui sistemas oficiais.
--
-- 1) FISCALIZACAO.CHECKLIST: JSON {"versao":1,"categoria":"...","itens":{"<id>":valor}} validado na API contra o
--    modelo da CategoriaFiscalizacao da demanda (modelos versionados no código, ChecklistFiscalizacao).
ALTER TABLE FISCALIZACAO ADD (
    CHECKLIST CLOB,
    CONSTRAINT CK_FISCALIZACAO_CHECKLIST_JSON CHECK (CHECKLIST IS NULL OR CHECKLIST IS JSON)
);

-- 2) FISCALIZACAO_FOTO: fotos de evidência da demanda em execução. O arquivo fica no volume (STORAGE_DIR), nunca
--    no banco; aqui só a chave opaca, o SHA-256 e os metadados. EXIF é informativo (nunca usado em autorização).
--    DISTANCIA_KM: Haversine até a coordenada da demanda ou até a borda do polígono (0 se dentro da área).
--    GPS_FORA_MT = TRUE quando o GPS do EXIF está fora da caixa envolvente de Mato Grosso (sinalização, não bloqueio).
CREATE TABLE FISCALIZACAO_FOTO (
    ID              NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
    DEMANDA_ID      NUMBER(19)          NOT NULL,
    CHAVE_ARQUIVO   VARCHAR2(200 CHAR)  NOT NULL,
    SHA256          VARCHAR2(64)        NOT NULL,
    MIME            VARCHAR2(20)        NOT NULL,
    TAMANHO         NUMBER(10)          NOT NULL,
    NOME_ORIGINAL   VARCHAR2(255 CHAR)  NOT NULL,
    EXIF_DATA_HORA  TIMESTAMP,
    EXIF_LATITUDE   NUMBER(9,6),
    EXIF_LONGITUDE  NUMBER(9,6),
    DISTANCIA_KM    NUMBER(10,3),
    GPS_FORA_MT     BOOLEAN             DEFAULT FALSE NOT NULL,
    AUTOR_ID        NUMBER(19)          NOT NULL,
    CRIADO_EM       TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_FISCALIZACAO_FOTO PRIMARY KEY (ID),
    CONSTRAINT UK_FISCALIZACAO_FOTO_CHAVE UNIQUE (CHAVE_ARQUIVO),
    CONSTRAINT CK_FISC_FOTO_MIME CHECK (MIME IN ('image/jpeg', 'image/png', 'image/webp')),
    CONSTRAINT CK_FISC_FOTO_TAMANHO CHECK (TAMANHO > 0),
    CONSTRAINT CK_FISC_FOTO_LAT CHECK (EXIF_LATITUDE IS NULL OR EXIF_LATITUDE BETWEEN -90 AND 90),
    CONSTRAINT CK_FISC_FOTO_LON CHECK (EXIF_LONGITUDE IS NULL OR EXIF_LONGITUDE BETWEEN -180 AND 180),
    CONSTRAINT CK_FISC_FOTO_GPS CHECK ((EXIF_LATITUDE IS NULL AND EXIF_LONGITUDE IS NULL)
        OR (EXIF_LATITUDE IS NOT NULL AND EXIF_LONGITUDE IS NOT NULL)),
    CONSTRAINT CK_FISC_FOTO_DIST CHECK (DISTANCIA_KM IS NULL OR DISTANCIA_KM >= 0),
    CONSTRAINT FK_FISC_FOTO_DEMANDA FOREIGN KEY (DEMANDA_ID) REFERENCES DEMANDA (ID),
    CONSTRAINT FK_FISC_FOTO_AUTOR FOREIGN KEY (AUTOR_ID) REFERENCES USUARIO (ID)
);
CREATE INDEX IX_FISC_FOTO_DEMANDA ON FISCALIZACAO_FOTO (DEMANDA_ID, CRIADO_EM);
CREATE INDEX IX_FISC_FOTO_AUTOR ON FISCALIZACAO_FOTO (AUTOR_ID);
