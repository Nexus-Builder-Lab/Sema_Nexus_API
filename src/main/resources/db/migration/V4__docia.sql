-- O arquivo fica no volume (STORAGE_DIR); o banco guarda só metadados, hash e o texto extraído.

CREATE TABLE DOCUMENTO (
    ID               NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
    TITULO           VARCHAR2(200 CHAR)  NOT NULL,
    DESCRICAO        VARCHAR2(2000 CHAR),
    CATEGORIA        VARCHAR2(60 CHAR)   NOT NULL,
    TIPO             VARCHAR2(60 CHAR)   NOT NULL,
    DATA_DOCUMENTO   DATE                NOT NULL,
    MUNICIPIO_ID     NUMBER(7),
    PALAVRAS_CHAVE   VARCHAR2(1100 CHAR),
    NOME_ARQUIVO     VARCHAR2(255 CHAR)  NOT NULL,
    MIME             VARCHAR2(100)       NOT NULL,
    TAMANHO          NUMBER(19)          NOT NULL,
    STORAGE_KEY      VARCHAR2(100)       NOT NULL,
    SHA256           VARCHAR2(64)        NOT NULL,
    TEXTO_EXTRAIDO   CLOB,
    RESPONSAVEL_ID   NUMBER(19)          NOT NULL,
    CRIADO_EM        TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    ATUALIZADO_EM    TIMESTAMP,
    EXCLUIDO_EM      TIMESTAMP,
    CONSTRAINT PK_DOCUMENTO PRIMARY KEY (ID),
    CONSTRAINT UK_DOCUMENTO_STORAGE_KEY UNIQUE (STORAGE_KEY),
    CONSTRAINT FK_DOCUMENTO_MUNICIPIO FOREIGN KEY (MUNICIPIO_ID) REFERENCES MUNICIPIO (ID),
    CONSTRAINT FK_DOCUMENTO_RESPONSAVEL FOREIGN KEY (RESPONSAVEL_ID) REFERENCES USUARIO (ID),
    CONSTRAINT CK_DOCUMENTO_TAMANHO CHECK (TAMANHO >= 0)
);

CREATE INDEX IX_DOCUMENTO_CATEGORIA ON DOCUMENTO (CATEGORIA);
CREATE INDEX IX_DOCUMENTO_DATA ON DOCUMENTO (DATA_DOCUMENTO);
CREATE INDEX IX_DOCUMENTO_MUNICIPIO_ID ON DOCUMENTO (MUNICIPIO_ID);
CREATE INDEX IX_DOCUMENTO_RESPONSAVEL_ID ON DOCUMENTO (RESPONSAVEL_ID);

CREATE TABLE DOCUMENTO_DEMANDA (
    DOCUMENTO_ID   NUMBER(19)  NOT NULL,
    DEMANDA_ID     NUMBER(19)  NOT NULL,
    VINCULADO_EM   TIMESTAMP   DEFAULT SYSTIMESTAMP NOT NULL,
    VINCULADO_POR  NUMBER(19)  NOT NULL,
    CONSTRAINT PK_DOCUMENTO_DEMANDA PRIMARY KEY (DOCUMENTO_ID, DEMANDA_ID),
    CONSTRAINT FK_DOCDEM_DOCUMENTO FOREIGN KEY (DOCUMENTO_ID) REFERENCES DOCUMENTO (ID),
    CONSTRAINT FK_DOCDEM_DEMANDA FOREIGN KEY (DEMANDA_ID) REFERENCES DEMANDA (ID),
    CONSTRAINT FK_DOCDEM_USUARIO FOREIGN KEY (VINCULADO_POR) REFERENCES USUARIO (ID)
);

CREATE INDEX IX_DOCDEM_DEMANDA_ID ON DOCUMENTO_DEMANDA (DEMANDA_ID);
CREATE INDEX IX_DOCDEM_VINCULADO_POR ON DOCUMENTO_DEMANDA (VINCULADO_POR);
